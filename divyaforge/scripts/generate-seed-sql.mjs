/**
 * Generates supabase/seed.sql from src/lib/catalog/data/catalog.json —
 * the bundled catalog and the DB can never drift because both come from
 * the same file. Idempotent (upserts).
 *
 * Usage: node scripts/generate-seed-sql.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(
  readFileSync(join(ROOT, "src/lib/catalog/data/catalog.json"), "utf8"),
);

const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const qj = (v) => `${q(JSON.stringify(v))}::jsonb`;
const qarr = (a) => `array[${a.map(q).join(", ")}]::text[]`;
const qn = (n) => (n === null || n === undefined ? "null" : String(n));

const lines = [
  "-- GENERATED by scripts/generate-seed-sql.mjs from catalog.json — do not edit by hand.",
  "",
];

for (const d of catalog.deities) {
  lines.push(
    `insert into public.deities (id, name_en, name_hi, tier, style_tags, forms, poses, body_zones) values (` +
      [q(d.id), q(d.name.en), q(d.name.hi), q(d.tier), qarr(d.styleTags), qj(d.forms), qj(d.poses), qj(d.bodyZones)].join(", ") +
      `)\n  on conflict (id) do update set name_en = excluded.name_en, name_hi = excluded.name_hi, tier = excluded.tier, style_tags = excluded.style_tags, forms = excluded.forms, poses = excluded.poses, body_zones = excluded.body_zones;`,
  );
}
lines.push("");

for (const p of catalog.parts) {
  lines.push(
    `insert into public.parts (id, deity_id, category, tab, slot, name_en, name_hi, mesh_url, thumbnail_url, color_zones, constraint_tags, price_volume, style_tags) values (` +
      [
        q(p.id), q(p.deityId), q(p.category), q(p.tab), q(p.slot),
        q(p.name.en), q(p.name.hi), q(p.meshUrl), q(p.thumbnailUrl),
        qj(p.colorZones), qarr(p.constraintTags), qn(p.priceVolume), qarr(p.styleTags),
      ].join(", ") +
      `)\n  on conflict (id) do update set deity_id = excluded.deity_id, category = excluded.category, tab = excluded.tab, slot = excluded.slot, name_en = excluded.name_en, name_hi = excluded.name_hi, mesh_url = excluded.mesh_url, thumbnail_url = excluded.thumbnail_url, color_zones = excluded.color_zones, constraint_tags = excluded.constraint_tags, price_volume = excluded.price_volume, style_tags = excluded.style_tags;`,
  );
}
lines.push("");

for (const c of catalog.constraints) {
  lines.push(
    `insert into public.constraints (id, deity_id, rule_type, part_tag, deity_style_tag, slot_side, max_count, reason_en, reason_hi) values (` +
      [
        q(c.id), q(c.deityId), q(c.ruleType), q(c.partTag),
        q(c.deityStyleTag ?? null), q(c.slotSide ?? null), qn(c.maxCount ?? null),
        q(c.reason.en), q(c.reason.hi),
      ].join(", ") +
      `)\n  on conflict (id) do update set deity_id = excluded.deity_id, rule_type = excluded.rule_type, part_tag = excluded.part_tag, deity_style_tag = excluded.deity_style_tag, slot_side = excluded.slot_side, max_count = excluded.max_count, reason_en = excluded.reason_en, reason_hi = excluded.reason_hi;`,
  );
}
lines.push("");

writeFileSync(join(ROOT, "supabase/seed.sql"), lines.join("\n"));
console.log(
  `seed.sql: ${catalog.deities.length} deities, ${catalog.parts.length} parts, ${catalog.constraints.length} constraints`,
);
